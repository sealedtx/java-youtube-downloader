package com.github.kiulian.downloader.model.subtitles;

/**
 * A subtitle (caption) track of a video.
 */
public final class SubtitleTrack {

    private final String languageCode;
    private final String name;
    private final boolean autoGenerated;
    private final boolean translatable;
    private final String url;

    public SubtitleTrack(String languageCode, String name, boolean autoGenerated, boolean translatable, String url) {
        this.languageCode = languageCode;
        this.name = name;
        this.autoGenerated = autoGenerated;
        this.translatable = translatable;
        this.url = url;
    }

    /** For example {@code en} or {@code pt-BR}. */
    public String languageCode() {
        return languageCode;
    }

    /** Display name, for example {@code English (auto-generated)}. */
    public String name() {
        return name;
    }

    /** True for YouTube's automatic speech recognition. */
    public boolean isAutoGenerated() {
        return autoGenerated;
    }

    /** True if YouTube can translate this track to other languages. */
    public boolean isTranslatable() {
        return translatable;
    }

    /** Download URL as YouTube sent it. */
    public String url() {
        return url;
    }

    @Override
    public String toString() {
        return languageCode + (autoGenerated ? " (auto)" : "");
    }
}
